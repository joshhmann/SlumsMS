#!/usr/bin/env python3
"""Writes slums.dll's built-in bounce block list (client repo src/bounce_zones_builtin.inc) from the
jump_quests category of src/main/java/soloMapling/BounceZones/bounce-zones.yaml.

    python3 tools/bounce/gen_client_zones.py [yaml] > <client>/src/bounce_zones_builtin.inc
    python3 tools/bounce/gen_client_zones.py --golden [yaml]   # the BOUNCE_ZONES_SYNC hex for the shipped yaml

The client uses the built-in list only until the server's login packet (LP 0x3737) arrives. Its native
test (tests/bounce_rules_test.cpp) decodes the --golden packet, which the server's BounceZonePacketsTest
also checks, and compares it with this list -- so an edit to jump_quests fails one side until both follow.
The parser covers the file's own shape (see the header of bounce-zones.yaml); entries as BounceZones parses.
"""
import re
import struct
import sys

DEFAULT = "src/main/java/soloMapling/BounceZones/bounce-zones.yaml"


def categories(path):
    cats, cur, in_maps = [], None, False
    for raw in open(path, encoding="utf-8"):
        line = raw.split(" #", 1)[0].rstrip() if not raw.lstrip().startswith("#") else ""
        if not line.strip():
            continue
        m = re.match(r"^  - name:\s*(\S+)", line)
        if m:
            cur = {"name": m.group(1), "maps": [], "enabled": False, "fj": False}
            cats.append(cur)
            in_maps = False
            continue
        m = re.match(r"^    (\w+):\s*(.*)$", line)
        if m and cur is not None:
            key, val = m.groups()
            in_maps = key == "maps"
            if key == "enabled":
                cur["enabled"] = val.strip() == "true"
            if key == "block_flash_jump":
                cur["fj"] = val.strip() == "true"
            continue
        m = re.match(r"^      - (\S+)$", line)
        if m and cur is not None and in_maps:
            cur["maps"].append(entry(m.group(1)))
    return cats


def entry(s):
    if re.fullmatch(r"\d{1,9}", s):
        return int(s), int(s)
    m = re.fullmatch(r"(\d{1,9})\s*-\s*(\d{1,9})", s)
    if m:
        return int(m.group(1)), int(m.group(2))
    m = re.fullmatch(r"(\d+)([xX]+)", s)
    if m and len(s) == 9:
        scale = 10 ** len(m.group(2))
        return int(m.group(1)) * scale, int(m.group(1)) * scale + scale - 1
    raise SystemExit(f"bad map entry {s!r}")


def merge(ranges):
    out = []
    for a, b in sorted(ranges):
        if out and a <= out[-1][1] + 1:
            out[-1][1] = max(out[-1][1], b)
        else:
            out.append([a, b])
    return out


def golden(cats, native=1050):
    bounce = merge([r for c in cats if c["enabled"] for r in c["maps"]])
    fj = merge([r for c in cats if c["enabled"] and c["fj"] for r in c["maps"]])
    b = struct.pack("<HBi", 0x3737, 1, native)
    for lst in (bounce, fj):
        b += struct.pack("<H", len(lst)) + b"".join(struct.pack("<ii", x, y) for x, y in lst)
    return b.hex()


def main(argv):
    gold = "--golden" in argv
    args = [a for a in argv if a != "--golden"]
    cats = categories(args[0] if args else DEFAULT)
    jq = next(c for c in cats if c["name"] == "jump_quests")
    if gold:
        print(golden(cats))
        return
    print("// Generated by the server's tools/bounce/gen_client_zones.py from bounce-zones.yaml jump_quests.")
    print("// Do not edit; regenerate. Checked by tests/bounce_rules_test.cpp against the server's golden packet.")
    for a, b in merge(jq["maps"]):
        print(f"{{{a}, {b}}},")


if __name__ == "__main__":
    main(sys.argv[1:])
