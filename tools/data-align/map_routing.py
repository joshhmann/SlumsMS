#!/usr/bin/env python3
"""Map routing: where a move into a map the server or the client can't load has to go instead (ticket s-maproute).

Reads the server WZ and writes src/main/resources/soloMapling/map-routing.tsv, the table server.maps.MapRouting
loads: one route per portal edge (or scripted warp) whose target is missing from Map.wz or on the client-crash list,
and one blocked_maps row per such target with its kind and the map a saved character or a warp of unknown origin
falls back to.

Correct means "where that portal was meant to lead", from the map's own data, first rule that fits wins and is
written in the row's reason column:

  1. manual       - a kept row from the previous table (its line ends with '# manual'); never recomputed
  2. return       - the target exists (client-crash): its info/forcedReturn, else its info/returnMap
  3. portal-pair  - a map whose portal is the exact counterpart of ours (its pn is our tn and its tn our pn)
  4. source-return- the source map's own info/returnMap: where that map sends a character back to, so a door into a
                    hole leads out of the map the player is standing in. Row '100 out03 70 -> 66 source-return' is an
                    example: 100's returnMap is 66 (not 65, which is 66's own returnMap), so the two rows are a chain
  5. street-town  - the nearest town (info/town=1) on the target's street (String.wz streetName)
  6. street-nearest - the nearest map on that street
  7. henesys      - 100000000

Every route must itself be a map that is in Map.wz and not blocked, and every row's reason is re-derived from the
data by check_reasons() independently of the rule that wrote it; the generator validates its own output and exits
non-zero instead of writing a table that would send a player into another broken map or that names a rule its route
does not follow.

    python3 tools/data-align/map_routing.py --wz /root/slums-nav-v70/wz \
        [--client-crash <the Client lane's list>] [--check]

The seed tools/data-align/client-crash-maps.txt is always read; --client-crash adds another list (repeatable) on top
of it, so the lane's audit file and our own confirmed rows can be passed together without either replacing the other.

--check prints the validation and the counts, and fails when the committed table is out of date, without
writing.
"""
import argparse
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "src/main/resources/soloMapling/map-routing.tsv"
CRASH = ROOT / "tools/data-align/client-crash-maps.txt"
HENESYS = 100000000
NO_TARGET = 999999999

# a literal warp in a script: pi.warp(103000101), cm.warp(910000000, 0) - not pi.getMapId() + 1
WARP = re.compile(r"\bwarp\(\s*(\d{3,9})\b")
BOT_WARP = re.compile(r'new WarpEdge\(\s*(\d+)\s*,\s*"([^"]*)"\s*,\s*(\d+)\s*,\s*(-?\d+)\s*\)')

HEADER_ROUTES = ("# Map routing (ticket s-maproute). Generated by tools/data-align/map_routing.py from Map.wz -"
                 " regenerate, don't hand-edit;\n"
                 "# a line that ends with '# manual' is kept by the generator.\n"
                 "# routes: from_map <TAB> portal_name|* <TAB> target_map <TAB> route_to_map <TAB>"
                 " route_to_portal <TAB> reason\n")
HEADER_BLOCKED = ("# blocked_maps: map <TAB> kind(missing|client-crash) <TAB> reason <TAB> fallback_map\n")


def leaves(node):
    """{name: value} of an imgdir's leaf children (string/int/float)."""
    return {c.get("name"): c.get("value") for c in node if c.get("value") is not None}


def read_maps(wz):
    """id -> {'info': {...}, 'portals': [{'pn','tn','tm','pt','script','index'}]} for every Map.wz image."""
    maps = {}
    for f in sorted((wz / "Map.wz" / "Map").glob("Map*/*.img.xml")):
        stem = f.name.split(".")[0]
        if not stem.isdigit():
            continue
        mapid = int(stem)
        entry = {"info": {}, "portals": []}
        root = ET.parse(f).getroot()
        for node in root:
            name = node.get("name")
            if name == "info":
                entry["info"] = leaves(node)
            elif name == "portal":
                for portal in node:
                    v = leaves(portal)
                    if "pn" not in v:  # later sections of a portal node are not portals
                        continue
                    v["index"] = portal.get("name", "")
                    entry["portals"].append(v)
        maps[mapid] = entry
    return maps


def read_names(wz):
    """id -> (street, name) from String.wz/Map.img."""
    names = {}
    for el in ET.parse(wz / "String.wz" / "Map.img.xml").getroot().iter("imgdir"):
        n = el.get("name", "")
        if len(n) == 9 and n.isdigit():
            mn, sn = el.find("string[@name='mapName']"), el.find("string[@name='streetName']")
            names[int(n)] = ((sn.get("value") if sn is not None else ""),
                             (mn.get("value") if mn is not None else ""))
    return names


def read_list(path):
    """Map ids from a list file: first token of every line, '#' starts a comment.

    Round 3: an id prefixed with '!' clears that map instead of listing it - the seed retires 410000350, which the
    Client lane's audit file still carries, because client build 10721 fixed its crash. Returns (listed, cleared)."""
    listed, cleared = [], []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        token = line.split()[0]
        if token.startswith("!"):
            cleared.append(int(token[1:]))
        else:
            listed.append(int(token))
    return listed, cleared


def script_edges(wz_root, mapid, portal):
    """Literal warp targets of the script a portal runs (its `script` attribute, else <map>.<index>.js)."""
    name = (portal.get("script") or "").strip()
    if not name:
        name = f"{mapid}.{portal['index']}"
    path = wz_root / "scripts" / "portal" / f"{name}.js"
    if not path.exists():
        return []
    return sorted({int(m.group(1)) for m in WARP.finditer(path.read_text(encoding="utf-8", errors="ignore"))})


def collect_edges(wz_root, wz, maps):
    """Every move the server can make into a map: (from_map, portal_name, target, source). Portal scripts resolve
    relative warp targets at run time, so only literal ids are seen here; the resolver catches the rest at run time."""
    edges = {}
    for mapid, entry in maps.items():
        for portal in entry["portals"]:
            pn = portal.get("pn", "")
            tm = int(portal.get("tm") or NO_TARGET)
            targets = [tm] if tm not in (NO_TARGET, 0, -1) else []
            targets += [t for t in script_edges(wz_root, mapid, portal) if t not in targets]
            for t in targets:
                edges[(mapid, pn, t)] = "portal"
    # the bots' curated scripted warps (soloMapling/ArtificialPlayer/BotTravelSystem/BotScriptedWarp.java)
    bot = ROOT / "src/main/java/soloMapling/ArtificialPlayer/BotTravelSystem/BotScriptedWarp.java"
    if bot.exists():
        for m in BOT_WARP.finditer(bot.read_text(encoding="utf-8")):
            edges[(int(m.group(1)), m.group(2), int(m.group(3)))] = "bot"
    # NPC / event scripts: the source map is whoever is talking to the NPC, so the row is keyed '*'
    loose = set()
    for d in ("npc", "event"):
        for f in sorted((wz_root / "scripts" / d).glob("*.js")):
            for m in WARP.finditer(f.read_text(encoding="utf-8", errors="ignore")):
                loose.add(int(m.group(1)))
    return edges, loose


class Router:
    def __init__(self, maps, names, blocked):
        self.maps, self.names, self.blocked = maps, names, blocked
        self.by_street = {}
        for mapid in maps:
            street = names.get(mapid, ("", ""))[0]
            if street:
                self.by_street.setdefault(street, []).append(mapid)
        # String.wz tags some maps with another era's street (a 2012 event map labelled "Midsummer Night's Forest"
        # next to 2005 Star Planet maps), so a street is only trusted inside the area that holds most of its maps.
        # Otherwise a reroute can jump continents: 910060100's "Victoria Road" tutorial next to Lady Syl's Room (350020015).
        self.street_area = {}
        for street, ids in self.by_street.items():
            loadable = [m for m in ids if m not in blocked]
            if loadable:
                areas = {}
                for m in loadable:
                    areas.setdefault(m // 100000000, 0)
                    areas[m // 100000000] += 1
                self.street_area[street] = min(areas, key=lambda a: (-areas[a], a))

    def loadable(self, mapid):
        return mapid in self.maps and mapid not in self.blocked

    def portal_named(self, mapid, name):
        if not name:
            return None
        for p in self.maps[mapid]["portals"]:
            if p.get("pn") == name:
                return p
        return None

    def arrival_portal(self, target, route, source, wanted):
        """The door on `route` a character should arrive at: the name the source portal expects (wanted) when the
        route map's door of that name leads back to the source (a genuine pair), else the route map's default spawn.
        Landing on a door that leads somewhere else would warp the character twice."""
        if wanted and source is not None:
            p = self.portal_named(route, wanted)
            if p is not None and int(p.get("tm") or NO_TARGET) == source:
                return wanted
        if self.portal_named(route, "sp"):
            return "sp"
        portals = self.maps[route]["portals"]
        return portals[0].get("pn") if portals else "0"

    def street_for(self, target, source=None):
        """The street a route is judged against: the target's own, else the source's (String.wz may not know the
        target at all)."""
        return self.names.get(target, ("", ""))[0] or self.names.get(source or 0, ("", ""))[0]

    def street_candidates(self, target, street):
        """(rule, map) for rules 5 and 6, best first: the street's nearest town, else its nearest map. Only maps
        inside the street's own area count, so a 2012 event map cannot pull a route across the world."""
        area = self.street_area.get(street)
        on_street = [m for m in self.by_street.get(street, [])
                     if self.loadable(m) and m != target and (area is None or m // 100000000 == area)]
        out = []
        for rule, take in (("street-town", lambda m: self.maps[m]["info"].get("town") == "1"),
                           ("street-nearest", lambda m: True)):
            out += [(rule, m) for m in sorted((m for m in on_street if take(m)), key=lambda m: (abs(m - target), m))]
        return out

    def route(self, target, source=None, portal=None):
        """(map, portal, reason) for a move into `target`; None when nothing loadable is known."""
        info = self.maps.get(target, {}).get("info", {})
        if target in self.maps:  # rule 2: the map exists (client-crash) - it knows where it sends you back to
            for key in ("forcedReturn", "returnMap"):
                back = int(info.get(key, NO_TARGET) or NO_TARGET)
                if back not in (NO_TARGET, target) and self.loadable(back):
                    return back, self.arrival_portal(target, back, source, (portal or {}).get("tn")), "return"
        if source is not None and portal and portal.get("tn"):  # rule 3: the counterpart door elsewhere
            pn, tn = portal.get("pn"), portal.get("tn")
            found = [m for m in self.maps
                     if self.loadable(m) and m != target
                     and any(p.get("pn") == tn and p.get("tn") == pn and int(p.get("tm") or NO_TARGET) == source
                             for p in self.maps[m]["portals"])]
            if len(found) == 1:
                return found[0], tn, "portal-pair"
        if source is not None:  # rule 4: the way back out of this dead end
            back = int(self.maps.get(source, {}).get("info", {}).get("returnMap", NO_TARGET) or NO_TARGET)
            if self.loadable(back):
                return back, self.arrival_portal(target, back, source, (portal or {}).get("tn")), "source-return"
        street = self.street_for(target, source)
        wanted = (portal or {}).get("tn")
        if street:  # rules 5 and 6: the street this door belongs to, inside that street's own area
            for rule, near in self.street_candidates(target, street):
                return near, self.arrival_portal(target, near, source, wanted), rule
        if self.loadable(HENESYS):  # rule 7
            return HENESYS, self.arrival_portal(target, HENESYS, source, wanted), "henesys"
        return None


def manual_rows(path):
    """Rows of the previous table whose line ends with '# manual', keyed by (from, portal, target)."""
    kept = {}
    if not path.exists():
        return kept
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip().endswith("# manual"):
            continue
        body = line.split("# manual")[0].rstrip()
        cols = body.split("\t")
        if len(cols) >= 6:
            kept[(cols[0], cols[1], cols[2])] = cols
    return kept


def check_reasons(router, rows, problems):
    """s-maproute round 2: a row's reason must be provable from the data on its own, not only from what route() said
    on the run that wrote it. Every label is re-derived here without calling route(), so a row that claims
    'source-return' but lands where the source never returns is a problem instead of a review finding."""
    for row in rows:
        frm, portal_name, target, lands, door, label = row[0], row[1], int(row[2]), int(row[3]), row[4], row[5]
        reason = label.replace(" (script)", "")
        if reason == "manual":
            continue
        where = f"{frm}/{portal_name} -> {target}"
        if lands not in router.maps or lands in router.blocked:
            problems.append(f"{where}: reason {label} but route {lands} is missing or blocked")
            continue
        if door != "0" and router.portal_named(lands, door) is None:
            problems.append(f"{where}: reason {label} but map {lands} has no portal {door}")
            continue
        source = None if frm == "*" else int(frm)
        if reason == "return":
            if target not in router.maps:
                problems.append(f"{where}: reason 'return' but Map.wz has no image for {target}")
                continue
            info = router.maps[target]["info"]
            backs = [int(info.get(k, NO_TARGET) or NO_TARGET) for k in ("forcedReturn", "returnMap")]
            if lands not in backs:
                problems.append(f"{where}: reason 'return' but {target} sends a character to {backs}, not {lands}")
        elif reason == "source-return":
            if source is None:
                problems.append(f"{where}: reason 'source-return' with no source map")
                continue
            back = int(router.maps.get(source, {}).get("info", {}).get("returnMap", NO_TARGET) or NO_TARGET)
            if target in router.maps:
                problems.append(f"{where}: reason 'source-return' but {target} has an image, so 'return' comes first")
            elif back != lands:
                problems.append(f"{where}: reason 'source-return' but map {source}'s returnMap is {back}, not {lands}")
        elif reason == "portal-pair":
            ours = router.portal_named(source, portal_name) if source is not None else None
            if ours is None:
                problems.append(f"{where}: reason 'portal-pair' but map {frm} has no portal {portal_name}")
                continue
            pn, tn = ours.get("pn"), ours.get("tn")
            twins = [m for m in router.maps
                     if router.loadable(m) and m != target
                     and any(p.get("pn") == tn and p.get("tn") == pn and int(p.get("tm") or NO_TARGET) == source
                             for p in router.maps[m]["portals"])]
            if twins != [lands]:
                problems.append(f"{where}: reason 'portal-pair' but the counterpart door is in {twins}, not {lands}")
        elif reason in ("street-town", "street-nearest"):
            street = router.street_for(target, source)
            if not street:
                problems.append(f"{where}: reason '{reason}' but String.wz knows no street for {target}")
                continue
            best = next((m for rule, m in router.street_candidates(target, street) if rule == reason), None)
            if best != lands:
                problems.append(f"{where}: reason '{reason}' but the street '{street}' gives {best}, not {lands}")
        elif reason == "henesys":
            if lands != HENESYS:
                problems.append(f"{where}: reason 'henesys' but the route is {lands}")
        else:
            problems.append(f"{where}: unknown reason '{label}'")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--wz", default="wz", help="server WZ directory (XML)")
    ap.add_argument("--client-crash", action="append", default=[], metavar="FILE",
                    help="another client-crash list, one map id per line (repeatable); the seed "
                         "tools/data-align/client-crash-maps.txt is always read too")
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--check", action="store_true",
                    help="validate, compare with the committed table, write nothing")
    a = ap.parse_args()

    wz = Path(a.wz)
    wz_root = ROOT  # scripts/ live in the repo, not in the WZ
    maps = read_maps(wz)
    names = read_names(wz)
    listed, cleared = read_list(CRASH)
    for f in a.client_crash:
        more, gone = read_list(Path(f))
        listed += more
        cleared += gone
    crash = sorted(set(listed) - set(cleared))
    for mapid in sorted(set(cleared) & set(listed)):
        print(f"note: client-crash map {mapid} is cleared by a '!' line", file=sys.stderr)

    def label(mapid):
        street, name = names.get(mapid, ("", ""))
        return f"{street} : {name}" if name else ("not in String.wz" if mapid not in names else name)

    edges, loose = collect_edges(wz_root, wz, maps)

    # what is blocked: a target the server has no image for, or one the client dies on
    blocked = {}
    for _, _, target in edges:
        if target not in maps:
            blocked[target] = "missing"
    for target in loose:
        if target not in maps:
            blocked[target] = "missing"
    for target in crash:
        blocked[target] = "client-crash"   # a client crash outranks "no image": both are blocked, this says why
        if target not in maps:
            print(f"note: client-crash map {target} is not in Map.wz either", file=sys.stderr)

    router = Router(maps, names, blocked)
    kept = manual_rows(Path(a.out))

    rows, problems = [], []
    for (source, portal_name, target), kind in sorted(edges.items()):
        if target not in blocked:
            continue
        if source in blocked:
            continue  # nobody starts a move inside a map they cannot stand in
        key = (str(source), portal_name, str(target))
        if key in kept:
            rows.append(kept[key] + ["manual"])
            continue
        portal = router.portal_named(source, portal_name) or {}
        got = router.route(target, source, portal)
        if got is None:
            problems.append(f"{source} portal {portal_name} -> {target}: no loadable route")
            continue
        route_map, route_portal, reason = got
        rows.append([str(source), portal_name, str(target), str(route_map), route_portal, reason])
    if loose:
        for target in sorted(t for t in loose if t in blocked):
            got = router.route(target)
            if got is None:
                problems.append(f"script -> {target}: no loadable fallback")
                continue
            rows.append(["*", "*", str(target), str(got[0]), got[1], got[2] + " (script)"])

    blocked_rows = []
    for target, kind in sorted(blocked.items()):
        got = router.route(target)
        if got is None:
            problems.append(f"blocked map {target}: no loadable fallback")
            continue
        reason = label(target) + (" (client list)" if kind == "client-crash" else "")
        blocked_rows.append([str(target), kind, reason, str(got[0])])

    # validate every route: it must be a map the server has and is not blocked itself
    for row in rows:
        route_map = int(row[3])
        if route_map not in maps:
            problems.append(f"route {row[0]}/{row[1]} -> {row[2]} lands on {route_map}, which is not in Map.wz")
        elif route_map in blocked:
            problems.append(f"route {row[0]}/{row[1]} -> {row[2]} lands on {route_map}, which is blocked")
        if row[0] != "*" and int(row[0]) not in maps:
            problems.append(f"row source {row[0]} is not in Map.wz")
        if row[0] != "*" and row[1] != "*" and router.portal_named(int(row[0]), row[1]) is None:
            problems.append(f"row source {row[0]} has no portal named {row[1]}")
        if route_map in maps and row[4] != "0" and router.portal_named(route_map, row[4]) is None:
            problems.append(f"route {row[0]}/{row[1]} -> {row[2]} names portal {row[4]}, absent on {route_map}")
    for row in blocked_rows:
        fallback = int(row[3])
        if fallback not in maps or fallback in blocked:
            problems.append(f"blocked map {row[0]} has fallback {fallback}, which is missing or blocked")

    # and every reason must be the rule that names it, proved from the data rather than from route()'s own output
    check_reasons(router, rows, problems)

    rows.sort(key=lambda r: (r[0] != "*", int(r[0]) if r[0] != "*" else 0, r[1], int(r[2])))
    text = HEADER_ROUTES + "#\n"
    text += "".join("\t".join(r) + "\n" for r in rows)
    text += "\n" + HEADER_BLOCKED + "#\n"
    text += "".join("\t".join(r) + "\n" for r in blocked_rows)

    missing = sum(1 for k in blocked.values() if k == "missing")
    print(f"{len(maps)} maps in Map.wz; {len(edges)} moves scanned; {len(rows)} routes; "
          f"{len(blocked_rows)} blocked maps ({missing} missing, {len(blocked_rows) - missing} client-crash)")
    stayed = sum(1 for r in rows if r[0] != "*" and r[0] == r[3])
    print(f"{stayed} routes are dead ends (route_to_map == from_map: the character stays with a message)")
    counts = {}
    for r in rows:
        key = r[5].replace(" (script)", "")
        counts[key] = counts.get(key, 0) + 1
    print("reasons: " + ", ".join(f"{k} {counts[k]}" for k in sorted(counts)))
    if problems:
        print(f"\n{len(problems)} problem(s), table not written:", file=sys.stderr)
        for p in problems:
            print("  " + p, file=sys.stderr)
        return 1
    out = Path(a.out)
    if a.check:
        print("valid: every route lands on a map Map.wz has and the client can load, and every reason"
              " matches the rule that names it")
        current = out.read_text(encoding="utf-8") if out.exists() else ""
        if current == text:
            print(f"{out.relative_to(ROOT) if out.is_relative_to(ROOT) else out} is current")
            return 0
        now = set(current.splitlines())
        want = set(text.splitlines())
        dropped = sorted(now - want)
        added = sorted(want - now)
        print(f"\n{out.relative_to(ROOT) if out.is_relative_to(ROOT) else out} is out of date "
              f"({len(added)} line(s) to add, {len(dropped)} to drop); run without --check", file=sys.stderr)
        for line in added[:20]:
            print("  + " + line, file=sys.stderr)
        for line in dropped[:20]:
            print("  - " + line, file=sys.stderr)
        return 1
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT) if out.is_relative_to(ROOT) else out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
