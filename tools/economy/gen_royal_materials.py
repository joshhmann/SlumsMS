#!/usr/bin/env python3
"""Explicit gap-fill for the five first-forge regional materials; no existing row is edited."""
import argparse
import csv
from pathlib import Path
import xml.etree.ElementTree as ET
from gen_bb_drops import write_sql
from wzitems import WzItems

PAIRS=((8210000,4000625),(8210001,4000626),(8210003,4000627),(8210004,4000628),(8210005,4000629))


def build(wz_path,repo):
    w=WzItems(wz_path)
    with (repo/'docs/economy/bb-drops/mobs.csv').open() as handle:
        inventory={int(r['mobid']):r for r in csv.DictReader(handle)}
    rows=[]
    for mob,item in PAIRS:
        if w.droppable(item) is not None:
            raise ValueError(f'{item}: material violates drop policy')
        row=inventory[mob];mid=int(row['first_map'])
        if row['boss']!='0' or int(row['exp'])<=0 or not 211060000<=mid<211070000:
            raise ValueError(f'{mob}: unexpected first-forge source')
        info=ET.parse(wz_path/'Mob.wz'/f'{mob:07d}.img.xml').getroot().find("imgdir[@name='info']")
        if info is None:raise ValueError(f'{mob}: missing info')
        flags={n.get('name'):n.get('value') for n in info if n.get('value') is not None}
        if flags.get('link') or int(flags.get('boss',0)) or int(flags.get('allyMob',0)) or int(flags.get('exp',0))<=0:
            raise ValueError(f'{mob}: not an ordinary source')
        life=ET.parse(wz_path/'Map.wz/Map/Map2'/f'{mid:09d}.img.xml').getroot().find("imgdir[@name='life']")
        if life is None or not any(n.find("*[@name='type']") is not None and n.find("*[@name='type']").get('value')=='m' and n.find("*[@name='id']") is not None and int(n.find("*[@name='id']").get('value'))==mob for n in life):
            raise ValueError(f'{mob}: missing placement')
        rows.append((mob,item,1,1,0,400000))
    return rows


def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--wz',type=Path,required=True)
    args=ap.parse_args();root=Path(__file__).resolve().parents[2]
    if Path.cwd().resolve()!=root:ap.error('Run from this repository root')
    rows=build(args.wz,root)
    write_sql(rows,[],'060-royal-crafting-materials','royal_materials_060_rows','royal_materials_060_new',
              '-- DRAFT 1.6.4: fill only missing first-forge regional material pairs. Five explicit source pairs.\n-- 1x chance400000; server applies its rate. Existing rows, including quest/card rows, are preserved.\n-- Generated by tools/economy/gen_royal_materials.py. TEST/source/real-client proof and release admission pending.\n',
              '-- Roll back only pairs introduced by060; preserve older drops. Reload drops afterward.\n')
    print('Generated060 for five source pairs; no DB accessed.')

if __name__=='__main__':main()
