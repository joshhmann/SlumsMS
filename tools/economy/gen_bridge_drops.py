#!/usr/bin/env python3
"""Generate the approved bridge's migration 061 and Nimble guide; never connects to a DB."""
import argparse
import json
from pathlib import Path

from audit_bridge_progression import ROOT, DOCS, audit
from audit_normal_gear import FAMILIES, WEAPONS

NAME = '061-normal-gear-bridge'
LEDGER = 'normal_bridge_061_rows'
DDL = f'''CREATE TABLE IF NOT EXISTS mapleroot_integration_migrations (
  migration_id varchar(100) PRIMARY KEY, applied_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS {LEDGER} (
  dropperid int NOT NULL, itemid int NOT NULL, drop_id bigint NULL,
  operation char(1) NOT NULL, old_chance int NULL, target_chance int NOT NULL,
  minimum_quantity int NOT NULL, maximum_quantity int NOT NULL,
  PRIMARY KEY (dropperid, itemid)
) ENGINE=InnoDB;
'''


def render_sql(rows):
    values = ',\n'.join(f"({r['dropperid']}, {r['itemid']}, {r['proposed_base_chance']})"
                        for r in sorted(rows, key=lambda r: (r['dropperid'], r['itemid'])))
    apply = f'''-- 1.6.4 approved normal 120-149 bridge: 226 pairs / 113 existing items.
-- Generated by tools/economy/gen_bridge_drops.py; edit the bridge manifest/rate policy.
-- Apply with game/drop writers stopped; reload the drop cache after deployment.
-- The live schema has UNIQUE(dropperid,itemid). Quest-only pairs are preserved, not converted.
-- A persistent intent journal makes reruns recoverable even when drop_data uses MyISAM.
{DDL}
CREATE TEMPORARY TABLE normal_bridge_061_targets (
  dropperid int NOT NULL, itemid int NOT NULL, chance int NOT NULL,
  PRIMARY KEY (dropperid,itemid));
INSERT INTO normal_bridge_061_targets (dropperid,itemid,chance) VALUES
{values};

-- Freeze the original ordinary row and quantity before raising a weak rate.
INSERT IGNORE INTO {LEDGER}
  (dropperid,itemid,drop_id,operation,old_chance,target_chance,minimum_quantity,maximum_quantity)
SELECT d.dropperid,d.itemid,d.id,'U',d.chance,n.chance,d.minimum_quantity,d.maximum_quantity
FROM drop_data d JOIN normal_bridge_061_targets n USING(dropperid,itemid)
WHERE d.questid=0 AND d.chance<n.chance;

-- Record intent before inserting; never take ownership of an older or quest-only pair.
INSERT IGNORE INTO {LEDGER}
  (dropperid,itemid,drop_id,operation,old_chance,target_chance,minimum_quantity,maximum_quantity)
SELECT n.dropperid,n.itemid,NULL,'I',NULL,n.chance,1,1 FROM normal_bridge_061_targets n
WHERE NOT EXISTS (SELECT 1 FROM drop_data d WHERE d.dropperid=n.dropperid AND d.itemid=n.itemid);

UPDATE drop_data d JOIN {LEDGER} r ON d.id=r.drop_id
SET d.chance=r.target_chance
WHERE r.operation='U' AND d.dropperid=r.dropperid AND d.itemid=r.itemid AND d.questid=0
  AND d.chance=r.old_chance AND d.minimum_quantity=r.minimum_quantity AND d.maximum_quantity=r.maximum_quantity;

INSERT INTO drop_data (dropperid,itemid,minimum_quantity,maximum_quantity,questid,chance)
SELECT r.dropperid,r.itemid,1,1,0,r.target_chance FROM {LEDGER} r
WHERE r.operation='I' AND r.drop_id IS NULL
  AND NOT EXISTS (SELECT 1 FROM drop_data d WHERE d.dropperid=r.dropperid AND d.itemid=r.itemid);

UPDATE {LEDGER} r JOIN drop_data d USING(dropperid,itemid)
SET r.drop_id=d.id WHERE r.operation='I' AND r.drop_id IS NULL AND d.questid=0
  AND d.chance=r.target_chance AND d.minimum_quantity=1 AND d.maximum_quantity=1;

DROP TEMPORARY TABLE normal_bridge_061_targets;
INSERT IGNORE INTO mapleroot_integration_migrations(migration_id) VALUES ('{NAME}');
'''
    rollback = f'''-- Guard by original row ID, pair, quantity, ordinary status and exact written chance.
-- Later operator edits are preserved. Apply/rollback only with game/drop writers stopped.
{DDL}
DELETE d FROM drop_data d JOIN {LEDGER} r ON d.id=r.drop_id
WHERE r.operation='I' AND d.dropperid=r.dropperid AND d.itemid=r.itemid AND d.questid=0
  AND d.chance=r.target_chance AND d.minimum_quantity=r.minimum_quantity AND d.maximum_quantity=r.maximum_quantity;
UPDATE drop_data d JOIN {LEDGER} r ON d.id=r.drop_id
SET d.chance=r.old_chance
WHERE r.operation='U' AND d.dropperid=r.dropperid AND d.itemid=r.itemid AND d.questid=0
  AND d.chance=r.target_chance AND d.minimum_quantity=r.minimum_quantity AND d.maximum_quantity=r.maximum_quantity;
DELETE FROM {LEDGER};
DELETE FROM mapleroot_integration_migrations WHERE migration_id='{NAME}';
'''
    return apply, rollback


def guide_data(config, items, proposal):
    result = {'families': []}
    for mask, family in FAMILIES.items():
        bands = []
        for band in config['bands']:
            selected = [i for i in items if i['band'] == band['name'] and
                        (i['itemid'] // 10000 in WEAPONS[mask] if i['slot'] == 'Weapon' else i['reqJob'] == mask)]
            bands.append({'name': band['name'], 'start': band['recommended_start'], 'equip': band['equip_band'],
                          'items': [{'id': i['itemid'], 'equip': i['reqLevel'],
                                     'chance': next(r['proposed_base_chance'] for r in proposal if r['itemid']==i['itemid']),
                                     'sources': [{'mob': r['dropperid'], 'map': r['mapid']} for r in proposal
                                                 if r['itemid'] == i['itemid']]} for i in selected]})
        result['families'].append({'mask': mask, 'name': family, 'bands': bands})
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--wz', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    if args.write and Path.cwd().resolve() != ROOT:
        parser.error('--write must run in this repository root')
    config = json.loads((DOCS / 'bridge-120-149.json').read_text())
    items, proposal, _, _ = audit(config, args.wz, [], 4, 300)
    sql, rollback = render_sql(proposal)
    guide = json.dumps(guide_data(config, items, proposal), indent=2) + '\n'
    args.output.mkdir(parents=True, exist_ok=True)
    for name, data in [(NAME + '.sql', sql), (NAME + '.rollback.sql', rollback), ('normalGearGuide.json', guide)]:
        (args.output / name).write_text(data)
    if args.write:
        (ROOT / 'database/migrations' / (NAME + '.sql')).write_text(sql)
        (ROOT / 'database/migrations' / (NAME + '.rollback.sql')).write_text(rollback)
        (ROOT / 'scripts/json/normalGearGuide.json').write_text(guide)
    print(json.dumps({'pairs': len(proposal), 'items': len(items), 'written': args.write}))


if __name__ == '__main__':
    main()
