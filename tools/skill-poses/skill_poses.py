"""Write the skill-pose fixture the bot attack tests read: every skill's Skill.wz "action" names, per-level "action"
and "weapon", from a server's XML Skill.wz (one ``<job>.img.xml`` per job, as the server's ``wz/`` directory holds it).

This is the data ``BotSkillActions`` reads from the live server's Skill.wz; the tests run without game data, so they
check the bots' attacks against this copy instead.

Usage:

    python3 tools/skill-poses/skill_poses.py --wz <Server>/wz \
        > src/test/resources/soloMapling/mapleroot-skill-poses.tsv
"""
import argparse
import os
import sys
import xml.etree.ElementTree as ET


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--wz", required=True, help="directory holding Skill.wz/")
    args = parser.parse_args()
    skill_dir = os.path.join(args.wz, "Skill.wz")
    rows = []
    for name in sorted(os.listdir(skill_dir)):
        if not name.endswith(".img.xml") or not name[:-8].isdigit():
            continue
        root = ET.parse(os.path.join(skill_dir, name)).getroot()
        skills = root.find("imgdir[@name='skill']")
        if skills is None:
            continue
        for skill in skills:
            try:
                skill_id = int(skill.get("name"))
            except (TypeError, ValueError):
                continue
            actions, weapon, levels = [], 0, []
            for child in skill:
                if child.get("name") == "action":
                    actions = [a.get("value") for a in child if a.get("value")]
                elif child.get("name") == "weapon":
                    weapon = int(child.get("value"))
                elif child.get("name") == "level":
                    for level in child:
                        for c in level:
                            if c.get("name") == "action" and c.get("value"):
                                levels.append((int(level.get("name")), c.get("value")))
            if actions or weapon or levels:
                level_text = ";".join(f"{lv}={a}" for lv, a in sorted(levels))
                rows.append(f"{skill_id}\t{weapon}\t{','.join(actions)}\t{level_text}")
    sys.stdout.write("# skill\tweapon\tactions\tlevel actions (generated by tools/skill-poses/skill_poses.py)\n")
    sys.stdout.write("\n".join(sorted(rows, key=lambda r: int(r.split("\t")[0]))) + "\n")


if __name__ == "__main__":
    main()
