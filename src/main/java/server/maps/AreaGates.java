package server.maps;

import client.Character;
import config.YamlConfig;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.Collections;
import java.util.HashSet;
import java.util.Set;

/**
 * Ticket 81 round 3 (owner 2026-10-28, draft): who may enter the post-Big-Bang areas.
 * <ul>
 *   <li>Future / Twilight Perion (271000000-273999999): level 120, or 2 rebirths as before.</li>
 *   <li>Lower Grandis (the lv 109-142 band: Pantheon, Savage Terminal's low streets, Sanctuary, Caravan Refuge, Fox
 *       Ridge, Cheong-woon Valley, Ristonia, Toolen City; listed in {@code soloMapling/lower-grandis-maps.txt},
 *       generated by tools/economy/gen_area_gates.py): level 120, or 3 rebirths.</li>
 *   <li>The rest of Grandis and Arcane River (400000000-460000000): 3 rebirths, unchanged.</li>
 * </ul>
 * Before this, Twilight Perion needed 2 rebirths and all of Grandis 3 (HyperTPHandler, the Henesys teleporter, the
 * Temple of Time portal). Players are checked by the Hyper Rock, the teleporter (9010002), the Temple of Time portal
 * and every unscripted portal ({@link GenericPortal}); bots keep their own rebirth-only rule (BotMapGates).
 */
public final class AreaGates {

    private static final Logger log = LoggerFactory.getLogger(AreaGates.class);
    public static final int OPEN_LEVEL = 120;
    static final String RESOURCE = "/soloMapling/lower-grandis-maps.txt";
    private static final Set<Integer> LOWER_GRANDIS = load();

    private AreaGates() {
    }

    public static boolean isFuture(int mapId) {
        return mapId >= 271000000 && mapId <= 273999999;
    }

    public static boolean isLowerGrandis(int mapId) {
        return LOWER_GRANDIS.contains(mapId);
    }

    /** Grandis and Arcane River outside the lower band: 3 rebirths. */
    public static boolean isRebirth3Area(int mapId) {
        return mapId >= 400000000 && mapId <= 460000000 && !isLowerGrandis(mapId);
    }

    /** Why a character of this level and rebirth count may not enter mapId, or null when it may. */
    public static String denyReason(int mapId, int level, int reborns) {
        if (isFuture(mapId) && level < OPEN_LEVEL && reborns < 2) {
            return "You need to be level " + OPEN_LEVEL + " (or Rebirth level 2) to enter the Future.";
        }
        if (isLowerGrandis(mapId) && level < OPEN_LEVEL && reborns < 3) {
            return "You need to be level " + OPEN_LEVEL + " (or Rebirth level 3) to enter this part of Grandis.";
        }
        if (isRebirth3Area(mapId) && reborns < 3) {
            return "You need to be Rebirth level 3 or higher to go there.";
        }
        return null;
    }

    /** The same for a character; GMs (level 2+) always pass. */
    public static String denyReason(Character chr, int mapId) {
        if (chr == null || chr.gmLevel() >= 2) {
            return null;
        }
        return denyReason(mapId, chr.getLevel(), rebirthsOf(chr));
    }

    public static boolean mayEnter(Character chr, int mapId) {
        return denyReason(chr, mapId) == null;
    }

    /** Character.getReborns throws while the rebirth system is off; then nobody has any. */
    static int rebirthsOf(Character chr) {
        if (YamlConfig.config == null || YamlConfig.config.server == null
                || !YamlConfig.config.server.USE_REBIRTH_SYSTEM) {
            return 0;
        }
        return chr.getReborns();
    }

    static Set<Integer> lowerGrandis() {
        return LOWER_GRANDIS;
    }

    private static Set<Integer> load() {
        try (InputStream in = AreaGates.class.getResourceAsStream(RESOURCE)) {
            if (in == null) {
                log.warn("{} is missing from the jar; lower Grandis stays rebirth-3", RESOURCE);
                return Collections.emptySet();
            }
            Set<Integer> out = new HashSet<>();
            BufferedReader r = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
            String line;
            while ((line = r.readLine()) != null) {
                String id = line.split("[\t#]", 2)[0].trim();
                if (!id.isEmpty()) {
                    out.add(Integer.parseInt(id));
                }
            }
            return Collections.unmodifiableSet(out);
        } catch (IOException | RuntimeException e) {
            log.error("cannot read {}; lower Grandis stays rebirth-3", RESOURCE, e);
            return Collections.emptySet();
        }
    }
}
