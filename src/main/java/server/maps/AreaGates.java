package server.maps;

import client.Character;
import config.YamlConfig;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.Collections;
import java.util.HashSet;
import java.util.Set;

/**
 * Ticket 81 round 3 (owner 2026-10-28, draft): who may enter the post-Big-Bang areas.
 * <ul>
 *   <li>Future / Twilight Perion (271000000-273999999): level 120, or the 1st rebirth (owner 2026-10-29; was 2).</li>
 *   <li>Lower Grandis (the lv 109-142 band: Pantheon, Savage Terminal's low streets, Sanctuary, Caravan Refuge, Fox
 *       Ridge, Cheong-woon Valley, Ristonia, Toolen City; listed in {@code soloMapling/lower-grandis-maps.txt},
 *       generated by tools/economy/gen_area_gates.py): level 120, or the 1st rebirth (owner 2026-10-29; was 3).</li>
 *   <li>Owner 2026-10-29: the rest of Grandis (Heliseum, Tyrant's Castle, the Fox Tree, Cernium, the rougher back
 *       streets of Savage Terminal) opens at the 1st rebirth and Arcane River at the 2nd, at any level (both were 3).</li>
 * </ul>
 * Before this, Twilight Perion needed 2 rebirths and all of Grandis 3 (HyperTPHandler, the Henesys teleporter, the
 * Temple of Time portal). Players are checked by the Hyper Rock, the teleporter (9010002), the Temple of Time portal
 * and every unscripted portal ({@link GenericPortal}); bots by BotMapGates.mayEnter(map, rebirths, level), which asks
 * this class, and by the teleporter rows of BotTransit.yaml (level 120 for the Future and lower Grandis towns).
 */
public final class AreaGates {

    private static final Logger log = LoggerFactory.getLogger(AreaGates.class);
    public static final int OPEN_LEVEL = 120;
    static final String RESOURCE = "/soloMapling/lower-grandis-maps.txt";
    private static final Set<Integer> LOWER_GRANDIS = load();

    private AreaGates() {
    }

    public static boolean isFuture(int mapId) {
        return mapId >= 271000000 && mapId <= 273999999;
    }

    public static boolean isLowerGrandis(int mapId) {
        return LOWER_GRANDIS.contains(mapId);
    }

    /** Rebirths that open the Future at any level (or level 120). */
    public static final int FUTURE_REBIRTHS = 1;   // owner 2026-10-29 (was 2): every 120 area opens at level 120 or any rebirth
    /** Rebirths that open lower Grandis at any level (or level 120). */
    public static final int LOWER_GRANDIS_REBIRTHS = 1;   // owner 2026-10-29 (was 3)
    /** Owner 2026-10-29: the deeper parts of Grandis open at the 1st rebirth, any level (was 3). */
    public static final int DEEPER_GRANDIS_REBIRTHS = 1;
    /** Owner 2026-10-29: Arcane River opens at the 2nd rebirth, any level (was 3). */
    public static final int ARCANE_REBIRTHS = 2;

    /**
     * Deeper Grandis: every Grandis map (400000000-419999999) outside lower-grandis-maps.txt - Heliseum, Tyrant's
     * Castle, the Fox Tree, Cernium, Savage Terminal's rougher back streets and the rest of the lv 175+ band.
     */
    public static boolean isDeeperGrandis(int mapId) {
        return mapId >= 400000000 && mapId < 420000000 && !isLowerGrandis(mapId);
    }

    /** Arcane River (and the rest of the old 420000000-460000000 rebirth-3 range, which has no maps today). */
    public static boolean isArcaneRiver(int mapId) {
        return mapId >= 420000000 && mapId <= 460000000;
    }

    /** The rebirths that open mapId at any level; 0 when it is not one of these areas. */
    public static int requiredRebirths(int mapId) {
        if (isFuture(mapId)) {
            return FUTURE_REBIRTHS;
        }
        if (isLowerGrandis(mapId)) {
            return LOWER_GRANDIS_REBIRTHS;
        }
        if (isDeeperGrandis(mapId)) {
            return DEEPER_GRANDIS_REBIRTHS;
        }
        if (isArcaneRiver(mapId)) {
            return ARCANE_REBIRTHS;
        }
        return 0;
    }

    /** Why a character of this level and rebirth count may not enter mapId, or null when it may. */
    public static String denyReason(int mapId, int level, int reborns) {
        if (isFuture(mapId) && level < OPEN_LEVEL && reborns < FUTURE_REBIRTHS) {
            return "You need to be level " + OPEN_LEVEL + " (or Rebirth level " + FUTURE_REBIRTHS
                    + ") to enter the Future.";
        }
        if (isLowerGrandis(mapId) && level < OPEN_LEVEL && reborns < LOWER_GRANDIS_REBIRTHS) {
            return "You need to be level " + OPEN_LEVEL + " (or Rebirth level " + LOWER_GRANDIS_REBIRTHS
                    + ") to enter this part of Grandis.";
        }
        if (isDeeperGrandis(mapId) && reborns < DEEPER_GRANDIS_REBIRTHS) {
            return "You need to be Rebirth level " + DEEPER_GRANDIS_REBIRTHS + " or higher to enter this part of Grandis.";
        }
        if (isArcaneRiver(mapId) && reborns < ARCANE_REBIRTHS) {
            return "You need to be Rebirth level " + ARCANE_REBIRTHS + " or higher to enter Arcane River.";
        }
        return null;
    }

    /** The same for a character; GMs (level 2+) always pass. */
    public static String denyReason(Character chr, int mapId) {
        if (chr == null || chr.gmLevel() >= 2) {
            return null;
        }
        return denyReason(mapId, chr.getLevel(), rebirthsOf(chr));
    }

    public static boolean mayEnter(Character chr, int mapId) {
        return denyReason(chr, mapId) == null;
    }

    /** Character.getReborns throws while the rebirth system is off; then nobody has any. */
    static int rebirthsOf(Character chr) {
        if (YamlConfig.config == null || YamlConfig.config.server == null
                || !YamlConfig.config.server.USE_REBIRTH_SYSTEM) {
            return 0;
        }
        return chr.getReborns();
    }

    static Set<Integer> lowerGrandis() {
        return LOWER_GRANDIS;
    }

    private static Set<Integer> load() {
        try (InputStream in = AreaGates.class.getResourceAsStream(RESOURCE)) {
            if (in == null) {
                log.warn("{} is missing from the jar; lower Grandis stays rebirth-3", RESOURCE);
                return Collections.emptySet();
            }
            Set<Integer> out = new HashSet<>();
            BufferedReader r = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
            String line;
            while ((line = r.readLine()) != null) {
                String id = line.split("[\t#]", 2)[0].trim();
                if (!id.isEmpty()) {
                    out.add(Integer.parseInt(id));
                }
            }
            return Collections.unmodifiableSet(out);
        } catch (IOException | RuntimeException e) {
            log.error("cannot read {}; lower Grandis stays rebirth-3", RESOURCE, e);
            return Collections.emptySet();
        }
    }
}
